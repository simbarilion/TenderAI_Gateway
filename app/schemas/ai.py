"""Схемы запроса и ответа генерации."""

from pydantic import BaseModel, ConfigDict, Field


class GenerateRequest(BaseModel):
    """Запрос пользователя."""

    model_config = ConfigDict(
        json_schema_extra={
            "examples": [
                {
                    "prompt": "Проанализируй техническое задание IT-тендера и оцени риски для подрядчика.\n\n "
                    "Заказчик: региональный портал госзакупок.\nСрок: 8 недель.\n "
                    "Бюджет: фиксированный, 2 400 000 ₽, без предоплаты, оплата по актам раз в месяц.\n\n "
                    "Нужно разработать:\n- backend на Python (FastAPI);\n- PostgreSQL;\n "
                    "- REST API для мониторинга закупок;\n- простой веб-интерфейс для операторов;\n "
                    "- Docker и docker-compose;\n- интеграцию с одним внешним API ЕИС (есть документация, "
                    "OAuth2, лимит 60 запросов/мин);\n- CI на GitHub Actions: lint и тесты.\n\n "
                    "Нефункциональные требования:\n- до 200 одновременных пользователей;\n "
                    "- доступ только по HTTPS;\n- хранить логи действий операторов 90 дней;\n "
                    "- критерии приемки: API по OpenAPI, покрытие тестами не меньше 60%, деплой одной "
                    "командой compose.\n\nНе указано: мобильное приложение, SLA, резервное копирование, "
                    "роли кроме «оператор» и «админ».\n\nСделай:\n1) факты отдельно от предположений;\n "
                    "2) недостающие требования в ТЗ;\n3) 5 главных рисков для подрядчика с влиянием на срок "
                    "и бюджет;\n4) минимальный состав команды;\n5) что уточнить у заказчика до подписания "
                    "договора.\nНе придумывай требования, которых нет в тексте."
                }
            ]
        }
    )

    prompt: str = Field(
        min_length=1,
        max_length=8000,
        description="Текст задания для модели: описание тендера, ТЗ или вопрос по рискам.",
        examples=["Проанализируй техническое задание и найди недостающие требования по безопасности и интеграциям."],
    )


class GenerateResponse(BaseModel):
    """Успешный ответ: текст модели и её идентификатор."""

    model_config = ConfigDict(
        json_schema_extra={
            "examples": [
                {
                    "response": "Основные риски: сжатый срок, фиксированный бюджет и три внешние интеграции.",
                    "model": "grok-3-mini",
                }
            ]
        }
    )

    response: str = Field(description="Текст ответа модели без системной инструкции.")
    model: str = Field(description="Имя модели, которую вернул провайдер или настройки Gateway.")
